#!/usr/bin/env bash
# Create your two PRIVATE data repos (task vault + progress notes) from the templates.
#
#   scripts/init-data-repos.sh [--vault DIR] [--notes DIR] [--empty] [--github OWNER]
#
#   --vault DIR     where to create the vault   (default: $ASSISTANT_VAULT or ~/assistant/vault)
#   --notes DIR     where to create the notes   (default: $ASSISTANT_NOTES or ~/assistant/notes)
#   --empty         no sample projects: one empty list per category in CATEGORIES (.env)
#   --github OWNER  also create PRIVATE GitHub repos OWNER/<dir name> and push (needs `gh auth login`)
#
# Each folder becomes its own git repo (branch main) with one initial commit, and the
# kit's skills are installed into the vault (.agents/skills, .claude/skills) so any
# coding agent opened there can manage tasks and notes. Writes .env from .env.example
# if you don't have one yet. Refuses to touch a folder that already exists and isn't empty.
set -euo pipefail
KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
[[ -f "$KIT/.env" ]] && { set -a; . "$KIT/.env"; set +a; } 2>/dev/null || true
VAULT="${ASSISTANT_VAULT:-$HOME/assistant/vault}"
NOTES="${ASSISTANT_NOTES:-$HOME/assistant/notes}"
EMPTY=0; OWNER=""
while (( $# )); do
  case "$1" in
    --vault) VAULT="$2"; shift ;;
    --notes) NOTES="$2"; shift ;;
    --empty) EMPTY=1 ;;
    --github) OWNER="$2"; shift ;;
    -h|--help) sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done
VAULT="${VAULT/#\~/$HOME}"; NOTES="${NOTES/#\~/$HOME}"

fresh() {  # fresh <dir>: refuse non-empty dirs
  if [[ -e "$1" && -n "$(ls -A "$1" 2>/dev/null)" ]]; then echo "refusing: $1 exists and is not empty" >&2; exit 1; fi
  mkdir -p "$1"
}
git_init() {  # git_init <dir> <message>
  git -C "$1" init -q
  git -C "$1" symbolic-ref HEAD refs/heads/main
  git -C "$1" add -A
  git -C "$1" -c user.name="${GIT_AUTHOR_NAME:-$(git config user.name || echo kit)}" \
               -c user.email="${GIT_AUTHOR_EMAIL:-$(git config user.email || echo kit@localhost)}" \
               commit -q -m "$2"
}

fresh "$VAULT"; fresh "$NOTES"
cp -R "$KIT/templates/vault/." "$VAULT/"
cp -R "$KIT/templates/notes/." "$NOTES/"
chmod +x "$NOTES/.notes/sync.sh"

if (( EMPTY )); then
  rm -rf "$VAULT/tasks" "$VAULT/memory/projects/"*.md "$NOTES"/*/
  cp "$KIT/templates/vault/memory/projects/README.md" "$VAULT/memory/projects/"
  printf '# Tasks\n\n## Today\n' > "$VAULT/TASKS.md"
  IFS=',' read -ra cats <<< "${CATEGORIES:-work:Work,side:Side,life:Life}"
  rows=""
  for c in "${cats[@]}"; do
    folder="${c%%:*}"; label="${c#*:}"; folder="${folder// /}"
    mkdir -p "$VAULT/tasks/$folder"
    printf '# %s\n\n## Active\n\n## Waiting On\n\n## Someday\n\n## Done\n' "$label" > "$VAULT/tasks/$folder/TASKS.md"
    rows+="| \`$folder/\` | $label | — |  |"$'\n'
  done
  printf '# Projects\n\nGenerated by the assistant dashboard from the vault.\n\n| Folder | Project | Code | Status |\n|---|---|---|---|\n%s' "$rows" > "$NOTES/PROJECTS.md"
fi

"$KIT/scripts/install-skills.sh" "$VAULT" >/dev/null
git_init "$VAULT" "vault: start from task-dashboard-kit template"
git_init "$NOTES" "notes: start from task-dashboard-kit template"
echo "created vault  $VAULT"
echo "created notes  $NOTES"

if [[ ! -f "$KIT/.env" ]]; then
  sed -e "s#^ASSISTANT_VAULT=.*#ASSISTANT_VAULT=$VAULT#" -e "s#^ASSISTANT_NOTES=.*#ASSISTANT_NOTES=$NOTES#" \
      "$KIT/.env.example" > "$KIT/.env"
  echo "wrote $KIT/.env (edit CATEGORIES etc. there)"
fi

if [[ -n "$OWNER" ]]; then
  for d in "$VAULT" "$NOTES"; do
    gh repo create "$OWNER/$(basename "$d")" --private --source "$d" --remote origin --push
  done
  echo "pushed both as PRIVATE repos under $OWNER"
else
  echo "local only. To back up/sync: create two PRIVATE GitHub repos and"
  echo "  git -C \"$VAULT\" remote add origin git@github.com:<you>/<vault-repo>.git && git -C \"$VAULT\" push -u origin main"
  echo "  (same for $NOTES), or re-run with --github <you> on fresh folders."
fi
